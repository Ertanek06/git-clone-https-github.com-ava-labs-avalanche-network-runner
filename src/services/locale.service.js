const dynamicTranslate = (core) => {
  if (uiPhraseMap[core]) return uiPhraseMap[core];
  let m = core.match(/^Toplam\s+(\d+)$/i);
  if (m) return `Total ${m[1]}`;
  m = core.match(/^(\d+)\s+kayıt$/i);
  if (m) return `${m[1]} records`;
  m = core.match(/^(\d+)\s+şablon\s*·\s*seçim anında ön izlenir$/i);
  if (m) return `${m[1]} templates · previewed instantly`;
  m = core.match(/^Detay\s*\((\d+)\s+fark\)$/i);
  if (m) return `Detail (${m[1]} changes)`;
  return core;
};
const translateExact = (value) => {
  const raw = String(value ?? ""),
    core = raw.trim();
  if (!core) return raw;
  const mapped = dynamicTranslate(core);
  return mapped === core ? raw : raw.replace(core, mapped);
};
export function translateRenderedHtml(html, locale) {
  if (normalizeLocale(locale) !== "en" || typeof html !== "string" || !html.includes("<")) return html;
  const protectedBlocks = [];
  let work = html.replace(/<(script|style|textarea|pre|code)\b[\s\S]*?<\/\1>/gi, (m) => {
    const token = `\u0000P${protectedBlocks.length}\u0000`;
    protectedBlocks.push(m);
    return token;
  });
  work = work
    .split(/(<[^>]+>)/g)
    .map((part) => {
      if (!part || part.startsWith("<")) {
        if (!part || !part.startsWith("<")) return part;
        return part.replace(
          /\b(title|aria-label|placeholder|data-confirm|data-message|data-title|data-confirm-title|data-confirm-message|data-confirm-ok)=(['"])(.*?)\2/gi,
          (all, name, q, val) => `${name}=${q}${translateExact(val)}${q}`
        );
      }
      return translateExact(part);
    })
    .join("");
  work = work.replace(/\u0000P(\d+)\u0000/g, (_, i) => protectedBlocks[Number(i)] || "");
  return work;
}
