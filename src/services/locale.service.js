const ascii = (v) =>
  String(v || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/ı/g, "i")
    .replace(/İ/g, "I")
    .replace(/[^a-z0-9]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .toUpperCase();
export function quoteDisplayNo(row = {}) {
  const quoteNo = String(row.quote_no || "");
  const revision = Number(row.revision_no || 0) > 0 ? ` / REV ${Number(row.revision_no)}` : "";
  return `${quoteNo}${revision}`;
}
export function quotePrintDisplayNo(row = {}, profile = {}) {
  const parse = (v) => {
    try {
      return typeof v === "string" ? JSON.parse(v || "{}") : v || {};
    } catch {
      return {};
    }
  };
  const customer = parse(row.customer_snapshot || row.customer_snapshot_json);
  const raw =
    customer.short_name ||
    customer.company_name ||
    profile.quote_prefix ||
    profile.short_name ||
    profile.company_name ||
    "";
  const prefix = ascii(raw).slice(0, 72).replace(/-+$/, "");
  const quoteNo = String(row.quote_no || "");
  const revision = Number(row.revision_no || 0) > 0 ? `-REV${Number(row.revision_no)}` : "";
  return prefix ? `${prefix}-${quoteNo}${revision}` : `${quoteNo}${revision}`;
}

